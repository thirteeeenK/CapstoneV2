    /**
     * 295 eval reviews (216 pos / 44 neu / 35 neg ground truth):
     * 235 original labeled rows + 60 hotel neu/neg rows (Neutral-Negative-Reviews.xlsx,
     * row 47 fixed to negative, ratings forced neg=1/neu=3).
     * All blind: sentiment='pending', ground_truth set from the prior blind
     * labeling exercise (see Evaluations/reviews_labeling_295.csv audit trail).
     * Target IDs assume a fresh seed (HotelSeeder/RoomSeeder/... run in fixed order).
     */
    public function run(): void
    {
        if (Review::whereHas('booking', fn ($q) => $q->where('booking_code', 'like', 'SEV-%'))->exists()) {
            $this->command?->info('Sentiment eval reviews already exist — skipping SentimentEvalSeeder.');

            return;
        }

        $this->ensureMatinloc();

        [$groupmates, $others] = $this->ensureUsers();
        $users = array_merge($groupmates, $others);

        $pool = $this->evalPool();

        $index = 0;

        foreach ($pool as $entry) {
            $user = $users[$index % count($users)];

            $booking = $this->createCompletedBooking($user, $entry);

            Review::create([
                'booking_id' => $booking->id,
                'booking_item_id' => $booking->items()->first()?->id,
                'user_id' => $user->id,
                'reviewable_type' => $entry['type'],
                'reviewable_id' => $entry['id'],
                'hotel_id' => $entry['hotel_id'],
                'room_id' => $entry['room_id'],
                'activity_id' => $entry['activity_id'],
                'package_id' => $entry['package_id'],
                'rating' => $entry['rating'],
                'comment' => $entry['comment'],
                'sentiment' => 'pending',
                'sentiment_score' => 0.0000,
                'ground_truth_sentiment' => $entry['ground_truth'],
                'extracted_keywords' => [],
                'is_verified_booking' => true,
                'is_published' => true,
                'created_at' => now()->subDays($index + 1)->subHours(rand(0, 12)),
                'updated_at' => now(),
            ]);

            $index++;
        }

        $this->command?->info("Seeded {$index} blind eval reviews (216 pos / 44 neu / 35 neg ground truth). Next: sentiment:run-ai -> sentiment:evaluate");
    }

